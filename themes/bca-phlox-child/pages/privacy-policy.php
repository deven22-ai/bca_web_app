<script>
document.addEventListener('DOMContentLoaded', function () {
    const sections = document.querySelectorAll('.bca-legal__content h2[id]');
    const tocLinks = document.querySelectorAll('.bca-legal__toc a');
    let isClickScrolling = false;
    let scrollTimer = null;

    function setActive(id) {
        tocLinks.forEach(link => {
            link.classList.remove('active');
            if (link.getAttribute('href') === '#' + id) {
                link.classList.add('active');
            }
        });
    }

    // Highlight on click — pause observer while scrolling to destination
    tocLinks.forEach(link => {
        link.addEventListener('click', function () {
            const id = this.getAttribute('href').replace('#', '');
            setActive(id);

            // Pause scroll-based highlighting
            isClickScrolling = true;
            clearTimeout(scrollTimer);

            // Resume scroll highlighting after scroll settles
            scrollTimer = setTimeout(() => {
                isClickScrolling = false;
            }, 1000); // 1s is enough for smooth scroll to finish
        });
    });

    // Highlight on scroll — but only if user is manually scrolling
    const observer = new IntersectionObserver((entries) => {
        if (isClickScrolling) return; // ignore during click scroll
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                setActive(entry.target.id);
            }
        });
    }, {
        rootMargin: '-10% 0px -80% 0px'
    });

    sections.forEach(section => observer.observe(section));
});
</script>